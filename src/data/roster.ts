// Build lookups, deduping by slug (some Japanese names collide above, but
// slugs are guaranteed unique by PokeAPI).
const _seen = new Set<string>();
export const UNIQUE_ROSTER: RosterEntry[] = FULL_ROSTER.filter((e) => {
  if (_seen.has(e.slug)) return false;
  _seen.add(e.slug);
  return true;
});

export function findRosterEntry(slug: string): RosterEntry | undefined {
  return UNIQUE_ROSTER.find((e) => e.slug === slug);
}
